# ---------------------------------------------------------------------------
# Orchestration
# ---------------------------------------------------------------------------
def run(output_dir: Optional[Path] = None) -> dict:
    """Runs the full F2.1B4-R reconciliation + agreement analysis and
    writes all Task 5 output artifacts. Returns a summary dict (also used
    directly by tests against an isolated ``output_dir``)."""
    out_dir = Path(output_dir) if output_dir is not None else DEFAULT_OUTPUT_DIR

    blind_judgments = load_blind_judgments()
    private_mapping = load_private_mapping()
    composite_scores = load_composite_scores()
    weight_sensitivity = load_weight_sensitivity()
    features = load_features()

    reconciled, rejected = reconcile(
        blind_judgments, private_mapping, composite_scores, weight_sensitivity, features
    )
    metrics = compute_agreement_metrics(reconciled)
    family_pairs = family_similarity_check(private_mapping)

    write_agreement_comparison_csv(reconciled, out_dir / "agreement_comparison.csv")
    disagreements = write_disagreement_report_csv(reconciled, out_dir / "disagreement_report.csv")
    write_agreement_metrics_json(metrics, family_pairs, out_dir / "agreement_metrics.json")
    png_written = write_confusion_matrix_png(
        metrics["confusion_matrix_algorithm_rows_chatgpt_cols"], out_dir / "confusion_matrix.png"
    )
    write_reconciliation_provenance_json(
        rejected, len(reconciled), out_dir / "reconciliation_provenance.json",
        source_paths={
            "blind_judgments_csv": BLIND_JUDGMENTS_CSV,
            "review_metadata_json": REVIEW_METADATA_JSON,
            "private_mapping_csv": PRIVATE_MAPPING_CSV,
            "train_composite_scores_v1_csv": COMPOSITE_SCORES_CSV,
            "train_features_v1_full_csv": FEATURES_CSV,
            "weight_sensitivity_v2_csv": WEIGHT_SENSITIVITY_CSV,
        },
    )

    return {
        "output_dir": str(out_dir),
        "n_reconciled": len(reconciled),
        "n_rejected": len(rejected),
        "n_disagreements": len(disagreements),
        "metrics": metrics,
        "family_pairs": family_pairs,
        "confusion_matrix_png_written": png_written,
    }


if __name__ == "__main__":
    result = run()
