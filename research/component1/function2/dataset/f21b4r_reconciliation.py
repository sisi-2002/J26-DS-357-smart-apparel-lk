"""F2.1B4-R -- reconciliation of the 30-sample ChatGPT blind visual-
complexity review against the algorithm's provisional (equal-weighted,
tertile-threshold) complexity labels.

Stage scope (per the F2.1B4-R task brief): this module ONLY joins the
already-imported ChatGPT judgments (``results/review/blind_judgments.csv``,
imported unchanged in a prior stage) to the algorithm's own stored outputs
via the PRIVATE S00X -> real ``image_id`` mapping, and computes descriptive
agreement statistics. It does NOT re-run or modify the review import, does
NOT re-run the SAM pilot, does NOT tune any feature weight or threshold
against this review, and does NOT freeze anything. Complexity thresholds
remain explicitly NOT FROZEN; human QC expert validation remains
explicitly PENDING -- this AI-assisted review is not a substitute for it.

Join chain (every edge keyed by a real, auditable identifier -- never a
reconstructed or guessed one):

    blind_judgments.csv (sample_id S001-S030, ChatGPT's judgment)
        --[sample_id == anonymous_sample_id]-->
    private_mapping.csv (the ONLY file holding the real identity of each
        blind sample; lives outside the repo's normal results tree, under
        exports/F2_1B3_chatgpt_20261018/private_DO_NOT_UPLOAD/, and was
        generated by F2.1B3's own blind-export script)
        --[original_sample_id == image_id]-->
    train_composite_scores_v1.csv (algorithm's ``proposed_group`` label +
        ``composite_score`` + per-feature z-scores, for the 1,747 ELIGIBLE
        TRAIN images only)
        --[image_id]--> weight_sensitivity_v2.csv (F2.1B3's 7-weighting-
        scheme stable/unstable classification, same 1,747-row population)
        --[image_id]--> train_features_v1_full.csv (raw
        luminance_variation / glcm_entropy / colour_variation, 1,900-row
        population -- superset of the eligible 1,747)

A blind sample is REJECTED (excluded from the reconciled table, and
explicitly reported, never silently dropped or guessed) if any edge in
this chain fails to resolve -- e.g. the private mapping has no entry for
that sample_id, or the mapped real ``image_id`` is absent from the
eligible-only composite-scores/weight-sensitivity tables (which would mean
that image was never part of the scored 1,747 population in the first
place).

ChatGPT's judgment label is additionally checked against the known valid
vocabulary (Simple/Moderate/High, or the literal "Cannot Assess", which
the review's own metadata confirms occurred 0/30 times in this review but
which the code handles defensively in case a future review produces it).
Rows whose judgment is "Cannot Assess" are kept in the reconciled table
(for transparency) but excluded from the core agreement statistics, which
require a comparable ordinal label on both sides.

Run (writes to the real `results/review/reconciliation_v1/` output
directory; read-only w.r.t. every INPUT file, including
`blind_judgments.csv` itself, which this stage must never modify):

    backend/.venv/Scripts/python.exe -m research.component1.function2.dataset.f21b4r_reconciliation
"""

