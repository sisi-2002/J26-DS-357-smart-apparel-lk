def write_agreement_comparison_csv(reconciled: list[dict], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=COMPARISON_CSV_FIELDS)
        writer.writeheader()
        for row in reconciled:
            writer.writerow({k: row.get(k) for k in COMPARISON_CSV_FIELDS})


DISAGREEMENT_CSV_FIELDS = COMPARISON_CSV_FIELDS + ["dominant_raw_feature_by_abs_zscore"]


def _dominant_feature(row: dict) -> str:
    zmap = {
        "luminance_variation": row["z_luminance_variation"],
        "glcm_entropy": row["z_glcm_entropy"],
        "colour_variation": row["z_colour_variation"],
    }
    zmap = {k: v for k, v in zmap.items() if v is not None}
    if not zmap:
        return "unknown"
    return max(zmap, key=lambda k: abs(zmap[k]))


def write_disagreement_report_csv(reconciled: list[dict], path: Path) -> list[dict]:
    """Writes the disagreement subset (algorithm_label != chatgpt_label,
    among assessable rows) and returns that subset (for reuse in the
    report-writing step)."""
    disagreements = [r for r in reconciled if r["chatgpt_assessable"] and not r["agree"]]
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=DISAGREEMENT_CSV_FIELDS)
        writer.writeheader()
        for row in disagreements:
            out = {k: row.get(k) for k in COMPARISON_CSV_FIELDS}
            out["dominant_raw_feature_by_abs_zscore"] = _dominant_feature(row)
            writer.writerow(out)
    return disagreements


