# ---------------------------------------------------------------------------
# Reconciliation (the join)
# ---------------------------------------------------------------------------
def reconcile(
    blind_judgments: Optional[list[dict]] = None,
    private_mapping: Optional[dict[str, dict]] = None,
    composite_scores: Optional[dict[str, dict]] = None,
    weight_sensitivity: Optional[dict[str, dict]] = None,
    features: Optional[dict[str, dict]] = None,
) -> tuple[list[dict], list[dict]]:
    """Join each blind ChatGPT judgment to the algorithm's real data.

    Returns ``(reconciled_rows, rejected_rows)``. A row is rejected (never
    guessed/interpolated) if the private mapping has no entry for its
    sample_id, or if the mapped real ``image_id`` is missing from the
    eligible composite-scores table, the weight-sensitivity table, or the
    features table. Every rejection records an explicit machine-readable
    ``reason`` string.
    """
    if blind_judgments is None:
        blind_judgments = load_blind_judgments()
    if private_mapping is None:
        private_mapping = load_private_mapping()
    if composite_scores is None:
        composite_scores = load_composite_scores()
    if weight_sensitivity is None:
        weight_sensitivity = load_weight_sensitivity()
    if features is None:
        features = load_features()

    reconciled: list[dict] = []
    rejected: list[dict] = []

    for j in blind_judgments:
        sid = j["sample_id"]

        mapping_row = private_mapping.get(sid)
        if mapping_row is None:
            rejected.append({"sample_id": sid, "image_id": None, "reason": "no_private_mapping_entry"})
            continue

        image_id = mapping_row["original_sample_id"]
        group_id = mapping_row["source_family_group_id"]

        cs_row = composite_scores.get(image_id)
        if cs_row is None:
            rejected.append({
                "sample_id": sid, "image_id": image_id,
                "reason": "image_id_not_in_eligible_composite_scores_table",
            })
            continue

        ws_row = weight_sensitivity.get(image_id)
        if ws_row is None:
            rejected.append({
                "sample_id": sid, "image_id": image_id,
                "reason": "image_id_not_in_weight_sensitivity_table",
            })
            continue

        feat_row = features.get(image_id)
        if feat_row is None:
            rejected.append({
                "sample_id": sid, "image_id": image_id,
                "reason": "image_id_not_in_features_table",
            })
            continue

        algorithm_label = cs_row["proposed_group"]

        # Internal consistency check: the composite-scores table's
        # proposed_group and the weight-sensitivity table's
        # group_baseline_equal column are both supposed to be the SAME
        # equal-weighted baseline label for the same image_id (they were
        # produced by two different F2.1B3 scripts from the same stored
        # calibration). Surfacing a mismatch here rather than silently
        # trusting one table would catch a real data-integrity problem.
        baseline_ws_label = ws_row.get("group_baseline_equal")
        labels_consistent = (baseline_ws_label == algorithm_label)

        chatgpt_label = j["judgment"]
        assessable = chatgpt_label in ORDERED_CATEGORIES

        reconciled.append({
            "sample_id": sid,
            "image_id": image_id,
            "source_family_group_id": group_id,
            "algorithm_label": algorithm_label,
            "algorithm_vs_weight_sensitivity_table_consistent": labels_consistent,
            "chatgpt_label": chatgpt_label,
            "chatgpt_assessable": assessable,
            "chatgpt_confidence": j["confidence"],
            "chatgpt_rationale": j["brief background-only rationale"],
            "chatgpt_limitations": j["limitations"],
            "composite_score": _to_float(cs_row["composite_score"]),
            "z_luminance_variation": _to_float(cs_row["z_luminance_variation"]),
            "z_glcm_entropy": _to_float(cs_row["z_glcm_entropy"]),
            "z_colour_variation": _to_float(cs_row["z_colour_variation"]),
            "boundary_adjacent_flag": _to_bool(cs_row.get("boundary_adjacent_flag", "False")),
            "weight_stable": _to_bool(ws_row["stable_across_all_weightings"]),
            "n_distinct_groups_across_7_weighting_schemes": int(ws_row["n_distinct_groups_across_schemes"]),
            "luminance_variation": _to_float(feat_row["luminance_variation"]),
            "glcm_entropy": _to_float(feat_row["glcm_entropy"]),
            "colour_variation": _to_float(feat_row["colour_variation"]),
            "agree": assessable and (algorithm_label == chatgpt_label),
        })

    return reconciled, rejected


