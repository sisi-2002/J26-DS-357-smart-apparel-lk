def load_blind_judgments(path: Path = BLIND_JUDGMENTS_CSV) -> list[dict]:
    """Load the 30 (never modified) ChatGPT blind judgments. Validates the
    sample_id set is exactly S001..S030 with no duplicates, and that every
    judgment label is in the known vocabulary -- raises loudly on anything
    else rather than silently coercing or dropping a row."""
    rows = _read_csv_rows(path)
    seen_ids = set()
    for row in rows:
        sid = row["sample_id"]
        if sid in seen_ids:
            raise ValueError(f"load_blind_judgments: duplicate sample_id {sid!r} in {path}")
        seen_ids.add(sid)
        judgment = row["judgment"]
        if judgment not in ALLOWED_JUDGMENT_LABELS:
            raise ValueError(
                f"load_blind_judgments: sample_id {sid!r} has judgment {judgment!r} "
                f"not in allowed vocabulary {sorted(ALLOWED_JUDGMENT_LABELS)}"
            )
        confidence = row["confidence"]
        if confidence not in ALLOWED_CONFIDENCE_LABELS:
            raise ValueError(
                f"load_blind_judgments: sample_id {sid!r} has confidence {confidence!r} "
                f"not in allowed vocabulary {sorted(ALLOWED_CONFIDENCE_LABELS)}"
            )
    return rows


def load_private_mapping(path: Path = PRIVATE_MAPPING_CSV) -> dict[str, dict]:
    """anonymous_sample_id (S00X) -> full private-mapping row (includes
    ``original_sample_id`` == the real train image_id, and
    ``source_family_group_id``)."""
    rows = _read_csv_rows(path)
