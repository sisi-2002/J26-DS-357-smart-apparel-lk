def _full_confusion_matrix(algo_labels: list[str], chatgpt_labels: list[str]) -> dict[str, dict[str, int]]:
    """Full 3x3 matrix (every cell present, including zeros), algorithm
    rows x ChatGPT columns, in the fixed ORDERED_CATEGORIES order."""
    matrix = {a: {c: 0 for c in ORDERED_CATEGORIES} for a in ORDERED_CATEGORIES}
    for a, c in zip(algo_labels, chatgpt_labels):
        matrix[a][c] += 1
    return matrix


def compute_agreement_metrics(reconciled: list[dict]) -> dict:
    """All Task 3 numbers, computed defensively: only rows with
    ``chatgpt_assessable=True`` feed the kappa/confusion-matrix/per-class
    statistics (a future review with "Cannot Assess" rows would be
    automatically excluded from these rather than silently miscounted)."""
    n_total = len(reconciled)
    n_not_assessable = sum(1 for r in reconciled if not r["chatgpt_assessable"])
    assessable_rows = [r for r in reconciled if r["chatgpt_assessable"]]
    n_assessable = len(assessable_rows)

    metrics: dict = {
        "n_total_reconciled": n_total,
        "n_not_assessable_excluded_from_core_stats": n_not_assessable,
        "n_assessable_used_for_core_stats": n_assessable,
        "sample_size_caveat": (
            "n={} is a small, intentionally-selected (not randomly sampled) set. "
            "These agreement numbers describe this specific 30-image blind-review "
            "batch ONLY and must NOT be extrapolated to claim validation of the "
            "full ~1,747-image training calibration or the complexity protocol "
            "in general.".format(n_total)
        ),
    }

    if n_assessable == 0:
        metrics["overall_exact_agreement_fraction"] = None
        metrics["confusion_matrix_algorithm_rows_chatgpt_cols"] = _full_confusion_matrix([], [])
        metrics["cohens_kappa_unweighted"] = None
        metrics["weighted_kappa_linear"] = None
        metrics["per_class"] = {}
        metrics["by_chatgpt_confidence"] = {}
        metrics["by_weight_stability"] = {}
        metrics["family_similarity_pairs"] = []
        return metrics

    algo_labels = [r["algorithm_label"] for r in assessable_rows]
    chatgpt_labels = [r["chatgpt_label"] for r in assessable_rows]

    n_agree = sum(1 for r in assessable_rows if r["agree"])
    metrics["overall_exact_agreement_fraction"] = n_agree / n_assessable
    metrics["overall_exact_agreement_percent"] = 100.0 * n_agree / n_assessable

    metrics["confusion_matrix_algorithm_rows_chatgpt_cols"] = _full_confusion_matrix(algo_labels, chatgpt_labels)

    metrics["cohens_kappa_unweighted"] = cohens_kappa(algo_labels, chatgpt_labels)
    metrics["weighted_kappa_linear"] = weighted_kappa(algo_labels, chatgpt_labels, ORDERED_CATEGORIES, "linear")
    metrics["weighted_kappa_method_note"] = (
        "Linear weighted kappa chosen over quadratic: with only 3 ordered "
        "categories, quadratic weighting would make a single Simple<->High "
        "disagreement count 4x an adjacent disagreement (vs. 2x under linear), "
        "which on n={} would let 1-2 far disagreements dominate the statistic. "
        "See complexity/inter_rater_agreement.py::weighted_kappa docstring.".format(n_assessable)
    )
    # Reported alongside, not substituted, for readers who want the
    # alternative convention.
    metrics["weighted_kappa_quadratic_for_reference_only"] = weighted_kappa(
        algo_labels, chatgpt_labels, ORDERED_CATEGORIES, "quadratic"
    )

    per_class = {}
    for cls in ORDERED_CATEGORIES:
        n_algo_cls = sum(1 for a in algo_labels if a == cls)
        n_chatgpt_cls = sum(1 for c in chatgpt_labels if c == cls)
        n_both_cls = sum(1 for a, c in zip(algo_labels, chatgpt_labels) if a == cls and c == cls)
        per_class[cls] = {
            "n_algorithm_assigned": n_algo_cls,
            "n_chatgpt_assigned": n_chatgpt_cls,
            "n_both_agree_on_this_class": n_both_cls,
            # "recall": of images the algorithm put in this class, what
            # fraction did ChatGPT also label this class?
            "recall_vs_algorithm": (n_both_cls / n_algo_cls) if n_algo_cls else None,
            # "precision": of images ChatGPT put in this class, what
            # fraction did the algorithm also label this class?
            "precision_vs_algorithm": (n_both_cls / n_chatgpt_cls) if n_chatgpt_cls else None,
        }
    metrics["per_class"] = per_class

    by_confidence: dict[str, dict] = {}
    for conf in sorted({r["chatgpt_confidence"] for r in assessable_rows}):
        rows_c = [r for r in assessable_rows if r["chatgpt_confidence"] == conf]
        n_c = len(rows_c)
        n_agree_c = sum(1 for r in rows_c if r["agree"])
        by_confidence[conf] = {
            "n": n_c,
            "n_agree": n_agree_c,
            "agreement_fraction": n_agree_c / n_c if n_c else None,
        }
    metrics["by_chatgpt_confidence"] = by_confidence

    by_stability: dict[str, dict] = {}
    for stable_flag, label in ((True, "stable_all_7_schemes"), (False, "unstable_at_least_1_scheme")):
        rows_s = [r for r in assessable_rows if r["weight_stable"] == stable_flag]
        n_s = len(rows_s)
        n_agree_s = sum(1 for r in rows_s if r["agree"])
        by_stability[label] = {
            "n": n_s,
            "n_agree": n_agree_s,
            "agreement_fraction": n_agree_s / n_s if n_s else None,
        }
    metrics["by_weight_stability"] = by_stability
    metrics["weight_stability_hypothesis_note"] = (
        "Hypothesis under test (not assumed true): algorithm-ChatGPT disagreement "
        "concentrates in images F2.1B3 already flagged as weight-UNSTABLE (i.e. "
        "group membership changes under at least 1 of 7 alternative weighting "
        "schemes). Compare the two agreement_fraction values above; a materially "
        "lower agreement_fraction for 'unstable' than 'stable' would support the "
        "hypothesis, but n={} is too small to draw a statistically firm "
        "conclusion either way -- report the numbers honestly, do not round them "
        "into a stronger claim than the sample size supports.".format(n_assessable)
    )

    return metrics


def family_similarity_check(private_mapping: dict[str, dict]) -> list[dict]:
    """Re-check the 3 visually-flagged near-duplicate pairs against the
    REAL source_family_group_id (not the visual impression alone)."""
    results = []
    for sid_a, sid_b in FLAGGED_SIMILARITY_PAIRS:
        row_a = private_mapping.get(sid_a)
        row_b = private_mapping.get(sid_b)
        group_a = row_a["source_family_group_id"] if row_a else None
        group_b = row_b["source_family_group_id"] if row_b else None
        results.append({
            "pair": [sid_a, sid_b],
            "group_id_a": group_a,
            "group_id_b": group_b,
            "shares_real_source_family": (group_a is not None and group_a == group_b),
        })
    return results


